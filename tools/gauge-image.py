#!/usr/bin/env python3
"""Turn a gauge data-flash dump (console `gaugedump 4000 4800`, lines "DF 4100: 55 00 ...") into
src/GaugeGoldenImage.h: the learned BQ28Z610 image the firmware replays onto every gauge that
still carries the stock chemistry (docs/GAUGE-CHEMISTRY.md).

    tools/gauge-image.py docs/gauge/dumps/<dump>.dfdump.txt --chem-id 0438

Only 0x4100-0x47FF goes into the image. 0x4000-0x40FF holds the per-unit calibration (cell /
pack / CC gains and offsets) and the lifetime counters, which must stay the unit's own.
"""
import sys, re, hashlib, datetime, argparse, pathlib

START, END = 0x4100, 0x4800
ap = argparse.ArgumentParser()
ap.add_argument("dump")
ap.add_argument("--chem-id", required=True, help="chemistry ID the gauge reports (MAC 0x0006), hex")
ap.add_argument("--out", default="src/GaugeGoldenImage.h")
a = ap.parse_args()

blocks = {}
for line in open(a.dump):
    m = re.match(r"DF ([0-9A-Fa-f]{4}): ((?:[0-9a-fA-F]{2} ?){32})", line.strip())
    if m:
        blocks[int(m.group(1), 16)] = bytes.fromhex(m.group(2).replace(" ", ""))
img = bytearray()
for addr in range(START, END, 32):
    if addr not in blocks:
        sys.exit(f"block 0x{addr:04X} missing in {a.dump}")
    img += blocks[addr]
assert len(img) == END - START

def u16(addr): return img[addr - START] | (img[addr - START + 1] << 8)
qmax = u16(0x4206); qmax_pack = u16(0x420A); update_status = img[0x420E - START]; ra_flag = u16(0x4100)
chem = int(a.chem_id, 16)
sha = hashlib.sha256(img).hexdigest()[:16]
src = pathlib.Path(a.dump).name
today = datetime.date.today().isoformat()

out = []
out.append("// GENERATED by tools/gauge-image.py - do not edit. The learned BQ28Z610 data-flash image")
out.append(f"// (0x{START:04X}-0x{END-1:04X}) from {src}, generated {today}, sha256 {sha}.")
out.append("// Replayed by BatteryManager::replayGaugeGoldenImage() (docs/GAUGE-CHEMISTRY.md). The")
out.append("// per-unit calibration and lifetime area 0x4000-0x40FF is deliberately not part of it.")
out.append("#pragma once")
out.append("#include <stdint.h>")
out.append("#include <stddef.h>")
out.append("")
out.append("namespace GaugeGoldenImage {")
out.append(f"constexpr uint16_t START = 0x{START:04X};")
out.append(f"constexpr size_t SIZE = {len(img)};")
out.append(f"constexpr uint16_t CHEM_ID = 0x{chem:04X};        // MAC 0x0006 after the replay")
out.append(f"constexpr uint16_t QMAX_CELL1_MAH = {qmax};      // 0x4206")
out.append(f"constexpr uint16_t QMAX_PACK_MAH = {qmax_pack};       // 0x420A")
out.append(f"constexpr uint8_t UPDATE_STATUS = 0x{update_status:02X};      // 0x420E")
out.append(f"constexpr uint16_t RA_FLAG = 0x{ra_flag:04X};         // 0x4100 (0x0055 = learned table)")
out.append(f'constexpr const char *SOURCE = "{src}";')
out.append(f'constexpr const char *SHA = "{sha}";')
out.append("")
out.append("extern const uint8_t DATA[SIZE]; // src/GaugeGoldenImage.cpp")
out.append("} // namespace GaugeGoldenImage")
pathlib.Path(a.out).write_text("\n".join(out) + "\n")
cpp = ["// GENERATED by tools/gauge-image.py - do not edit (see GaugeGoldenImage.h).",
       '#include "GaugeGoldenImage.h"', "", "namespace GaugeGoldenImage {", "const uint8_t DATA[SIZE] = {"]
for i in range(0, len(img), 16):
    addr = START + i
    cpp.append(f"    /* 0x{addr:04X} */ " + ", ".join(f"0x{b:02x}" for b in img[i:i+16]) + ",")
cpp += ["};", "} // namespace GaugeGoldenImage"]
pathlib.Path(a.out).with_suffix(".cpp").write_text("\n".join(cpp) + "\n")
print(f"{a.out}: {len(img)} bytes, chem 0x{chem:04X}, Qmax {qmax}/{qmax_pack}, Update Status 0x{update_status:02X}, Ra flag 0x{ra_flag:04X}, sha {sha}")
